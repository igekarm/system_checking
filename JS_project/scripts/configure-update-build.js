import { createPrivateKey, createPublicKey } from "node:crypto";
import { writeFile } from "node:fs/promises";
const privateKeyBase64=process.env.UPDATE_SIGNING_PRIVATE_KEY_BASE64;
if(!privateKeyBase64)throw new Error("UPDATE_SIGNING_PRIVATE_KEY_BASE64 is required");
const privateKey=createPrivateKey(Buffer.from(privateKeyBase64,"base64"));
const publicKeyPem=createPublicKey(privateKey).export({type:"spki",format:"pem"});
const source=`// Generated by configure-update-build.js; contains public data only.\nexport const updateConfig=Object.freeze(${JSON.stringify({publicKeyPem})});\n`;
await writeFile(new URL("../desktop/src/update-config.js",import.meta.url),source,{mode:0o600});
console.log("Desktop public update configuration generated");
